"""The exceptions the SDK raises. Catch `PayfurlError` for all of them."""

from __future__ import annotations

from enum import IntEnum
from typing import Any


class PayfurlError(Exception):
    """Every error the SDK raises."""


class APIError(PayfurlError):
    """The API answered with an error status: a decline, a validation error, a conflict, a server error.

    The API's error body (services/api `Error`) is in `body`, and its fields are attributes. `error_code` is the
    payFURL error code (https://docs.payfurl.com/errorcodes). `is_retryable` says whether the same request may
    succeed later.
    """

    def __init__(self, message: str, *, status_code: int, body: Any = None) -> None:
        super().__init__(message)
        self.message = message
        self.status_code = status_code
        self.body = body
        error = body if isinstance(body, dict) else {}
        code = error.get("code")
        self.error_code: int | None = code if isinstance(code, int) else None
        retryable = error.get("isRetryable")
        # A body that isn't the API's (a load balancer's 502, say): worth retrying only if the server failed.
        self.is_retryable: bool = retryable if isinstance(retryable, bool) else status_code >= 500 or status_code == 429
        self.type: str | None = error.get("type")
        self.resource: str | None = error.get("resource")
        self.details: dict[str, str] | None = error.get("details")
        self.gateway_code: str | None = error.get("gatewayCode")
        self.gateway_message: str | None = error.get("gatewayMessage")
        self.charge_id: str | None = error.get("chargeId")
        self.trace_id: str | None = error.get("traceId")

    def __str__(self) -> str:
        code = f", error code {self.error_code}" if self.error_code is not None else ""
        return f"{self.message} (HTTP {self.status_code}{code})"


class AuthenticationError(APIError):
    """HTTP 401 or 403: the key is wrong, or can't call this endpoint (a public key, say)."""


class NotFoundError(APIError):
    """HTTP 404: no such charge, customer, ... on this account."""


class APIConnectionError(PayfurlError):
    """The request didn't get a response: DNS, connection refused, TLS, a dropped connection."""


class APITimeoutError(APIConnectionError):
    """The request took longer than the client's `timeout`."""


